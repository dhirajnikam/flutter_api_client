import 'package:build/build.dart';
import 'package:source_gen/source_gen.dart';

import 'api_spec_entry.dart';
import 'package_import.dart';

/// build_runner entry point: emits a `$generatedSpec` getter for the
/// top-level variable annotated with `@ApiSpecEntry`.
Builder apiSpecBuilder(BuilderOptions options) =>
    SharedPartBuilder([_ApiSpecGenerator()], 'api_spec_entry');

class _ApiSpecGenerator extends GeneratorForAnnotation<ApiSpecEntry> {
  @override
  String generateForAnnotatedElement(
    dynamic element,
    ConstantReader annotation,
    BuildStep buildStep,
  ) {
    final name = element.name as String;
    return '''
// Generated by flutter_api_client — do not edit.
// Run `dart run build_runner build` to regenerate.

ApiSpec get $generatedSpecGetter => $name;
''';
  }
}

/// Emits a standalone `.test.g.dart` smoke-test scaffold next to the annotated file.
Builder apiSpecTestBuilder(BuilderOptions options) => _ApiSpecTestBuilder();

class _ApiSpecTestBuilder implements Builder {
  @override
  Map<String, List<String>> get buildExtensions => {
        '.dart': ['.test.g.dart'],
      };

  @override
  Future<void> build(BuildStep buildStep) async {
    if (!await buildStep.resolver.isLibrary(buildStep.inputId)) return;
    final library = await buildStep.resolver.libraryFor(buildStep.inputId);
    final reader = LibraryReader(library);
    const checker =
        TypeChecker.typeNamed(ApiSpecEntry, inPackage: 'flutter_api_client');
    final annotated = reader.annotatedWith(checker).toList();
    if (annotated.isEmpty) return;

    final content = buildApiSpecSmokeTestSource(
      importPath: packageImportFromLibPath(
        buildStep.inputId.package,
        buildStep.inputId.path,
      ),
      specSymbol: annotated.first.element.name!,
    );
    await buildStep.writeAsString(
      buildStep.inputId.changeExtension('.test.g.dart'),
      content,
    );
  }
}

/// Source of the smoke test [apiSpecTestBuilder] writes for [specSymbol].
String buildApiSpecSmokeTestSource({
  required String importPath,
  required String specSymbol,
}) {
  return '''
// GENERATED CODE - DO NOT MODIFY BY HAND
// Run `dart run build_runner build` to regenerate.
// ignore_for_file: depend_on_referenced_packages

import 'package:flutter_test/flutter_test.dart';
import '$importPath';

void main() {
  test('spec loads without error', () {
    expect($specSymbol, isNotNull);
    expect($specSymbol.endpoints, isNotEmpty);
  });

  group('Endpoint registration', () {
    for (final ep in $specSymbol.endpoints) {
      test('\${ep.method} \${ep.path} is registered', () {
        expect(ep.path, startsWith('/'));
        expect(ep.method, isNotEmpty);
      });
    }
  });
}
''';
}
